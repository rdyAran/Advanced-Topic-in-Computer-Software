def format_context(chunks):
    return "\n\n".join(
        CONTEXT_ITEM_TEMPLATE.format(
            n=i, category=c.get("category", "-"),
            question=c["question"], answer=c["answer"])
        for i, c in enumerate(chunks, start=1)
    )


def format_history(turns):
    lines = []
    for t in turns:
        lines.append(f"ผู้ใช้: {t['question']}")
        lines.append(f"ผู้ช่วย: {t['answer']}")
    return "\n".join(lines)
